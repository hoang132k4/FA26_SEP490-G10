package com.jlpp.modules.manager.flashcards;

import com.jlpp.modules.manager.flashcards.model.ManagerFlashcard;
import com.jlpp.modules.manager.flashcards.repository.ManagerFlashcardRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.JdbcTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

@JdbcTest
@ActiveProfiles("test")
@Import(ManagerFlashcardRepository.class)
class ManagerFlashcardRepositoryTest {

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Autowired
    private ManagerFlashcardRepository repository;

    @BeforeEach
    void createFlashcardTable() {
        jdbcTemplate.execute("""
                CREATE TABLE flashcards (
                    flashcard_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    lesson_id BIGINT NOT NULL,
                    front_content TEXT,
                    back_content TEXT,
                    vocabulary VARCHAR NOT NULL,
                    reading VARCHAR,
                    meaning TEXT NOT NULL,
                    example_sentence TEXT,
                    jlpt_level VARCHAR,
                    review_status VARCHAR,
                    creator_id BIGINT,
                    custom_deck_name VARCHAR,
                    is_custom BOOLEAN NOT NULL DEFAULT FALSE
                )
                """);
    }

    @Test
    void insertsReadsAndUpdatesExistingFlashcardColumns() {
        ManagerFlashcard flashcard = new ManagerFlashcard();
        flashcard.setLessonId(7L);
        flashcard.setFrontContent("学生");
        flashcard.setBackContent("học sinh");
        flashcard.setVocabulary("学生");
        flashcard.setReading("がくせい");
        flashcard.setMeaning("học sinh");
        flashcard.setExampleSentence("学生です。");
        flashcard.setJlptLevel("N5");
        flashcard.setReviewStatus("NEW");
        flashcard.setCreatorId(3L);
        flashcard.setCustomDeckName("N5");
        flashcard.setCustom(true);

        ManagerFlashcard inserted = repository.insert(flashcard);
        ManagerFlashcard loaded = repository.findById(inserted.getFlashcardId()).orElseThrow();

        assertTrue(inserted.getFlashcardId() > 0);
        assertEquals("学生", loaded.getVocabulary());
        assertEquals("がくせい", loaded.getReading());
        assertEquals(3L, loaded.getCreatorId());
        assertTrue(loaded.isCustom());
        loaded.setMeaning("người học");
        assertTrue(repository.update(loaded));
        assertEquals("người học", repository.findById(loaded.getFlashcardId()).orElseThrow().getMeaning());
        assertFalse(repository.update(missingFlashcard()));
    }

    private ManagerFlashcard missingFlashcard() {
        ManagerFlashcard flashcard = new ManagerFlashcard();
        flashcard.setFlashcardId(999L);
        flashcard.setLessonId(7L);
        flashcard.setVocabulary("不存在");
        flashcard.setMeaning("không tồn tại");
        return flashcard;
    }
}
